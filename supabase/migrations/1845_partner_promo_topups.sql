-- Ad-hoc top-ups of channel partner promotion credits (ARCHITECTURE §6.5 渠道商推广积分「临时追加」,
-- the Owner 2026-11-22): in a partner's first month there are no sales yet, so an admin can add
-- promotion credits by hand at any time. A top-up is a promotion grant like the monthly one: free
-- pool of the org owner's own account, never the org pool, and what is left of it is taken back at
-- the end of its UTC month by the same daily expiry pass (1847). It is not a monthly sheet and the
-- monthly formula never reads it (base, bonus and clawback are unchanged by a top-up).
--
-- This file only adds structure: a new table, plus one ledger kind and one audit action widened
-- from what they are now. Code running before the deploy never reads them.

do $$
declare
  v_kinds text[];
begin
  select array_agg(m[1] order by ord) into v_kinds
    from pg_constraint c,
         regexp_matches(pg_get_constraintdef(c.oid), '''([a-z0-9_]+)''', 'g') with ordinality as t(m, ord)
   where c.conrelid = 'public.credit_ledger'::regclass and c.conname = 'credit_ledger_kind_check';
  if v_kinds is null or cardinality(v_kinds) < 10 or not 'partner_promo_expire' = any(v_kinds) then
    raise exception 'credit_ledger_kind_check not found or unreadable';
  end if;
  if not 'partner_promo_topup' = any(v_kinds) then v_kinds := array_append(v_kinds, 'partner_promo_topup'); end if;
  execute 'alter table public.credit_ledger drop constraint credit_ledger_kind_check';
  execute 'alter table public.credit_ledger add constraint credit_ledger_kind_check check (kind in ('
    || (select string_agg(quote_literal(k), ',' order by o) from unnest(v_kinds) with ordinality u(k, o)) || '))';
end;
$$;

do $$
declare
  v_actions text[];
begin
  select array_agg(m[1] order by ord) into v_actions
    from pg_constraint c,
         regexp_matches(pg_get_constraintdef(c.oid), '''([a-z0-9_]+)''', 'g') with ordinality as t(m, ord)
   where c.conrelid = 'public.admin_audit_log'::regclass and c.conname = 'admin_audit_log_action_check';
  if v_actions is null or cardinality(v_actions) < 10 or not 'partner_promo_confirm' = any(v_actions) then
    raise exception 'admin_audit_log_action_check not found or unreadable';
  end if;
  if not 'partner_promo_topup' = any(v_actions) then v_actions := array_append(v_actions, 'partner_promo_topup'); end if;
  execute 'alter table public.admin_audit_log drop constraint admin_audit_log_action_check';
  execute 'alter table public.admin_audit_log add constraint admin_audit_log_action_check check (action in ('
    || (select string_agg(quote_literal(a), ',' order by o) from unnest(v_actions) with ordinality u(a, o)) || '))';
end;
$$;

-- One row per top-up (period = the UTC month it was made in and expires at the end of). The
-- recipient is the org owner at that moment. `request_key` is generated by the admin's form: a
-- second submit of the same form finds its row and grants nothing (the ledger key
-- partner_promo_topup:<id> is a second guard). The expiry columns work as on partner_promo_grants:
-- expired_basis is what was left when last measured, so a late refund is taken back only once.
create table public.partner_promo_topups (
  id bigint generated always as identity primary key,
  org_id uuid not null references public.orgs(id),
  period text not null check (period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  recipient_user_id uuid not null references public.profiles(id),
  credits integer not null check (credits between 1 and 100000),
  reason text not null check (length(btrim(reason)) between 1 and 500),
  request_key uuid not null unique,
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  expired_at timestamptz,
  expired_credits integer check (expired_credits >= 0),
  expired_basis integer check (expired_basis >= 0)
);
-- The tab's list (newest month first), the expiry pass (due ones and the week after) and the
-- per-account bucket the expiry measures together with the monthly grant of the same month.
create index partner_promo_topups_list_idx on public.partner_promo_topups(period desc, id desc);
create index partner_promo_topups_expiry_idx on public.partner_promo_topups(expires_at);
create index partner_promo_topups_bucket_idx on public.partner_promo_topups(recipient_user_id, expires_at);
alter table public.partner_promo_topups enable row level security;
revoke all on public.partner_promo_topups from public, anon, authenticated, service_role;
grant select on public.partner_promo_topups to service_role;
