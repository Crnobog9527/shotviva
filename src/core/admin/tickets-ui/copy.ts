export function ticketErrorText(code: string): string {
  return code === 'CONFLICT' || code === 'INVALID_INPUT' || code === 'NOT_FOUND' || code === 'IMAGE_TOO_LARGE' || code === 'IMAGE_UNSUPPORTED'
    ? TICKETS_COPY.errors[code]
    : TICKETS_COPY.errors.generic
}
