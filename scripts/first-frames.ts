/**
 * The hero photos' first frames: a small AVIF of each page's phone photo as a data: URI, written
 * to src/site/content/first-frames.generated.ts. The hero paints it with the document itself, so
 * the first screen's largest picture needs no request of its own (core/content/blocks/photo-pair).
 *
 *   pnpm images:first-frames        # after adding or replacing a hero phone photo
 */
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

import sharp from 'sharp'

// One entry per hero `before` picture (home and the three landing pages, both languages).
const SOURCES = ['/home/hero-set-phone.webp', '/cases/sneaker-phone.webp', '/cases/pet-phone.webp', '/cases/menu-fish-phone.webp']

// 288 px: at least as many pixels as the plate has CSS pixels on a phone (about 190 wide) and on
// a desktop (268 wide), so the browser counts the frame, not the later full picture, as the
// plate's first complete paint. Quality 45 keeps each frame near 7 KB, which the HTML carries
// twice on the home page.
const WIDTH = 288
const QUALITY = 45
// The menu fish photo is busier (steam, chilies, steel): a lower quality keeps it under 9 KB.
const QUALITY_FOR: Readonly<Record<string, number>> = { '/cases/menu-fish-phone.webp': 38 }

async function main() {
  const entries: string[] = []
  const hashes: string[] = []
  for (const src of SOURCES) {
    const input = await readFile(join(process.cwd(), 'public', src))
    hashes.push(`  '${src}': '${createHash('sha256').update(input).digest('hex')}',`)
    const frame = await sharp(input).resize({ width: WIDTH }).avif({ quality: QUALITY_FOR[src] ?? QUALITY, effort: 9 }).toBuffer()
    entries.push(`  '${src}': 'data:image/avif;base64,${frame.toString('base64')}',`)
    process.stdout.write(`${src}: ${frame.length} bytes\n`)
  }
  const file = [
    '// Generated by scripts/first-frames.ts (pnpm images:first-frames). Do not edit by hand.',
    'export const FIRST_FRAMES: Readonly<Record<string, string>> = {',
    ...entries,
    '}',
    '',
    '// SHA-256 of each source picture when its frame was made: a picture replaced under the same',
    '// file name fails first-frames.test.ts until the frames are regenerated.',
    'export const FIRST_FRAME_SOURCES: Readonly<Record<string, string>> = {',
    ...hashes,
    '}',
    '',
  ].join('\n')
  await writeFile(join(process.cwd(), 'src/site/content/first-frames.generated.ts'), file)
}

main().catch((error: unknown) => {
  process.stderr.write(`first-frames failed: ${error instanceof Error ? error.message : String(error)}\n`)
  process.exit(1)
})
