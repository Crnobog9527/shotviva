/**
 * Regenerates supabase/schema.sql, the one readable snapshot of the database (AGENTS §5).
 *
 *   supabase start      # or `supabase db reset` after adding a migration
 *   pnpm db:schema
 *
 * The snapshot is the public and admin schemas exactly as the migrations leave them, plus the triggers
 * that public functions hang on tables outside public (e.g. on_auth_user_created on
 * auth.users), which a public-only dump would miss. CI rebuilds the database from the
 * migrations, reruns this and fails if the committed file differs, so regenerate and commit
 * it with every migration (on a same-repo PR, CI commits the regenerated file itself, T88). Use
 * the CLI version CI pins (.github/actions/supabase-cli): another pg_dump version may format the
 * dump differently.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

import { Client } from 'pg'

const OUTPUT = resolve('supabase/schema.sql')

const HEADER = `-- Generated by \`pnpm db:schema\` from supabase/migrations. Do not edit by hand:
-- add a migration, reset the local database and regenerate (AGENTS §5).
`

// Non-internal triggers on tables outside public whose function lives in public.
const FOREIGN_TRIGGERS_SQL = `
  select pg_get_triggerdef(t.oid) || ';' as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_proc p on p.oid = t.tgfoid
    join pg_namespace pn on pn.oid = p.pronamespace
   where not t.tgisinternal and n.nspname <> 'public' and pn.nspname = 'public'
   order by n.nspname, c.relname, t.tgname`

function cli(args: string[], stderr: 'inherit' | 'ignore' = 'inherit'): string {
  return execFileSync('supabase', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', stderr] })
}

// Same stack `db dump --local` reads (this directory's config, or SUPABASE_WORKDIR).
function localDbUrl(): string {
  const line = cli(['status', '-o', 'env'], 'ignore')
    .split('\n')
    .find((entry) => entry.startsWith('DB_URL='))
  if (!line) throw new Error('No local database: run `supabase start` first')
  return line.slice('DB_URL='.length).replace(/^"|"$/g, '')
}

// admin holds the Owner's support views (ARCHITECTURE §10); it is not exposed to the Data API.
const SCHEMAS = ['public', 'admin']

function schemaDump(): string {
  // pg_dump 17.6+ wraps dumps in \restrict lines carrying a random token; drop them so
  // the snapshot only changes when the schema does.
  return cli(['db', 'dump', '--local', '--schema', SCHEMAS.join(',')])
    .split('\n')
    .filter((line) => !/^\\(un)?restrict /.test(line))
    .join('\n')
    .trim()
}

async function foreignTriggers(): Promise<string[]> {
  const client = new Client({ connectionString: localDbUrl() })
  await client.connect()
  try {
    // An empty search_path makes pg_get_triggerdef schema-qualify the function name.
    await client.query("set search_path = ''")
    const { rows } = await client.query<{ def: string }>(FOREIGN_TRIGGERS_SQL)
    return rows.map((row) => row.def)
  } finally {
    await client.end()
  }
}

async function main() {
  const triggers = await foreignTriggers()
  const sections = [HEADER, schemaDump()]
  if (triggers.length > 0) {
    sections.push(`-- Triggers on tables outside public that call public functions.\n\n${triggers.join('\n\n')}`)
  }
  writeFileSync(OUTPUT, `${sections.join('\n\n')}\n`)
  process.stdout.write(`Wrote ${OUTPUT}\n`)
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`)
  process.exit(1)
})
