import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'

// Which source files the public pages (marketing, sign-in, the 404s) can load: everything their
// route files import, statically or with import(), followed to the end. globals-public.css gives
// Tailwind exactly this list to read class names from (src/app/public-sources.generated.css).

export const GENERATED = 'src/app/public-sources.generated.css'

const ROUTE_FILES = new Set(['page.tsx', 'layout.tsx', 'not-found.tsx', 'error.tsx', 'loading.tsx', 'template.tsx', 'default.tsx'])
const PUBLIC_GROUPS = ['src/app/[locale]/(marketing)', 'src/app/[locale]/(auth)']
// Rendered outside any route group: the root layout and the pages that stand in for a missing or
// failed one.
const ROOT_FILES = ['src/app/[locale]/layout.tsx', 'src/app/[locale]/not-found.tsx', 'src/app/[locale]/error.tsx', 'src/app/global-not-found.tsx', 'src/app/global-error.tsx']

const IMPORT = /(?:\bfrom\s+|\bimport\s*\(\s*|\bimport\s+)["']([^"']+)["']/g
const CANDIDATES = ['', '.ts', '.tsx', '/index.ts', '/index.tsx']

function routeFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return routeFiles(path)
    return ROUTE_FILES.has(entry.name) ? [path] : []
  })
}

export function publicEntries(root: string): string[] {
  return [...PUBLIC_GROUPS.flatMap((group) => routeFiles(join(root, group))), ...ROOT_FILES.map((file) => join(root, file))].sort()
}

function resolveImport(root: string, from: string, specifier: string): string | null {
  const base = specifier.startsWith('@/') ? join(root, 'src', specifier.slice(2)) : specifier.startsWith('.') ? resolve(dirname(from), specifier) : null
  if (!base) return null
  for (const suffix of CANDIDATES) {
    const file = base + suffix
    if (existsSync(file) && statSync(file).isFile()) return file
  }
  return null
}

// Type-only imports are followed too: reading a file that renders nothing costs nothing, and a
// missed file would cost a missing style.
export function reachableSources(root: string): string[] {
  const seen = new Set<string>()
  const queue = publicEntries(root)
  for (let file = queue.pop(); file; file = queue.pop()) {
    if (seen.has(file) || !/\.tsx?$/.test(file)) continue
    seen.add(file)
    for (const match of readFileSync(file, 'utf8').matchAll(IMPORT)) {
      const next = resolveImport(root, file, match[1])
      if (next && !seen.has(next)) queue.push(next)
    }
  }
  return [...seen].map((file) => relative(root, file).split(sep).join('/')).sort()
}

// @source takes a glob, where [locale] would be a character class and (marketing) a group: each
// of those characters becomes `*` (`*locale*/*marketing*/…`), which matches the one it replaced.
// (`?` in its place matched nothing in Tailwind 4.3: the pricing page's classes went missing.)
const globSafe = (path: string) => path.replace(/[[\]()]/g, '*')

export function generatedCss(root: string): string {
  const fromDir = dirname(join(root, GENERATED))
  const lines = reachableSources(root).map((file) => `@source "${globSafe(relative(fromDir, join(root, file)).split(sep).join('/'))}";`)
  return ['/* Generated by scripts/public-css-sources.ts (pnpm css:sources). Do not edit by hand. */', ...lines, ''].join('\n')
}
